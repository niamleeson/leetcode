const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = (process.argv[2] || 'http://127.0.0.1:5193/leetcode/').replace(/\/?$/, '/');
const directory = process.env.SEARCH_SCREENSHOTS_DIR || '/tmp/leetcode-all-search-ui';
fs.mkdirSync(directory, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-gpu'] });
  const errors = [];
  const results = [];
  const contexts = [];
  const makePage = async width => {
    const context = await browser.newContext({ viewport: { width, height: 900 }, ...(width < 600 ? { isMobile: true, hasTouch: true } : {}) });
    contexts.push(context);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('requestfailed', request => { if (request.failure()?.errorText !== 'net::ERR_ABORTED') errors.push(`${request.url()}: ${request.failure()?.errorText}`); });
    page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()}: ${response.url()}`); });
    return page;
  };
  const input = page => page.getByRole('searchbox', { name: 'Search all problems', exact: true });
  const cards = page => page.locator('main a[href^="#/problem/"]');
  const pages = page => page.getByRole('navigation', { name: 'Problem result pages', exact: true });
  const params = page => new URLSearchParams(page.url().split('?')[1] || '');
  const visible = async (page, id) => { const link = page.locator(`main a[href="#/problem/${id}"]`); await link.waitFor(); assert.equal(await link.count(), 1, `Problem ${id} is reachable`); };
  const overflow = async page => {
    const sizes = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, body: document.body.scrollWidth }));
    assert.ok(sizes.document <= sizes.viewport + 1 && sizes.body <= sizes.viewport + 1, JSON.stringify(sizes));
  };
  const setLight = async page => {
    await page.getByRole('button', { name: 'Open menu', exact: true }).click();
    await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
    await page.getByRole('button', { name: 'Close menu', exact: true }).click();
    await page.waitForFunction(() => document.documentElement.classList.contains('light') && document.querySelector('aside').getBoundingClientRect().right <= 1);
  };
  try {
    const page = await makePage(1280);
    const bodies = [];
    page.on('request', request => { if (/\/(?:solutions\/[^/]+|catalog\/[^/]+\/\d+)\.json(?:\?|$)/.test(request.url())) bodies.push(request.url()); });
    await page.goto(`${base}#/problems?page=82`);
    await input(page).waitFor();
    assert.match(await pages(page).innerText(), /Page 83 of /);
    assert.ok(await cards(page).count() > 0 && await cards(page).count() <= 50);
    await input(page).pressSequentially('#3934');
    await visible(page, 3934);
    assert.equal(await input(page).inputValue(), '#3934');
    assert.equal(params(page).get('q'), '#3934');
    assert.equal(await cards(page).count(), 1);
    assert.equal(params(page).has('page'), false);
    await input(page).fill('  tWo   SuM  ');
    await visible(page, 1);
    await visible(page, 167);
    await input(page).fill(' #1352 PREFIX SUM ');
    await visible(page, 1352);
    assert.equal(await cards(page).count(), 1);
    await input(page).fill('easy');
    await pages(page).getByText(/Page 1 of /).waitFor();
    assert.equal(await cards(page).count(), 50);
    const firstPage = await cards(page).first().getAttribute('href');
    await pages(page).getByRole('button', { name: 'Next', exact: true }).click();
    await pages(page).getByText(/Page 2 of /).waitFor();
    assert.equal(params(page).get('q'), 'easy');
    assert.equal(params(page).get('page'), '1');
    assert.equal(await cards(page).count(), 50);
    const secondPage = await cards(page).first().getAttribute('href');
    assert.notEqual(secondPage, firstPage);
    await pages(page).getByRole('button', { name: 'Prev', exact: true }).click();
    await pages(page).getByText(/Page 1 of /).waitFor();
    assert.equal(await cards(page).first().getAttribute('href'), firstPage);
    await pages(page).getByRole('button', { name: 'Next', exact: true }).click();
    await pages(page).getByText(/Page 2 of /).waitFor();
    await page.getByRole('button', { name: 'Clear search', exact: true }).click();
    await pages(page).getByText(/Page 1 of /).waitFor();
    assert.equal(params(page).has('q'), false);
    assert.equal(params(page).has('page'), false);
    assert.equal(await cards(page).first().getAttribute('href'), '#/problem/1');
    await input(page).fill('#3934');
    await page.locator('main').getByRole('button', { name: 'Easy', exact: true }).click();
    await page.getByText('No problems match your search and filters.', { exact: true }).waitFor();
    assert.equal(await cards(page).count(), 0);
    await page.getByText('No problems match your search and filters.', { exact: true }).waitFor();
    await page.locator('main').getByRole('button', { name: 'Hard', exact: true }).click();
    await visible(page, 3934);
    await page.locator('main').getByRole('button', { name: 'Solved', exact: true }).click();
    await page.getByText('No problems match your search and filters.', { exact: true }).waitFor();
    assert.equal(await cards(page).count(), 0);
    await page.locator('main').getByRole('button', { name: 'Unseen', exact: true }).click();
    await visible(page, 3934);
    await page.getByRole('button', { name: 'Clear search', exact: true }).click();
    await pages(page).getByText(/Page 1 of /).waitFor();
    assert.equal(params(page).get('difficulty'), 'Hard');
    assert.equal(params(page).get('status'), 'unseen');
    assert.equal(params(page).has('q'), false);
    await page.locator('main').getByRole('button', { name: 'All', exact: true }).nth(1).click();
    await page.locator('main').getByRole('button', { name: 'All', exact: true }).nth(0).click();
    await input(page).fill('no_such_problem_9283746');
    await page.getByText('No problems match your search and filters.', { exact: true }).waitFor();
    assert.equal(params(page).has('status'), false, 'Typing must not restore a just-cleared status filter');
    assert.equal(params(page).has('difficulty'), false, 'Typing must not restore a just-cleared difficulty filter');
    assert.equal(await cards(page).count(), 0);
    assert.equal(await pages(page).count(), 0);
    await page.getByText('No problems match your search and filters.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Clear search', exact: true }).click();
    await pages(page).getByText(/Page 1 of /).waitFor();
    await input(page).fill('easy');
    await pages(page).getByText(/Page 1 of /).waitFor();
    await pages(page).getByRole('button', { name: 'Next', exact: true }).click();
    await pages(page).getByText(/Page 2 of /).waitFor();
    const retainedUrl = page.url();
    const retainedFirst = await cards(page).first().getAttribute('href');
    await page.reload();
    await input(page).waitFor();
    assert.equal(await input(page).inputValue(), 'easy');
    assert.equal(await cards(page).first().getAttribute('href'), retainedFirst);
    assert.equal(params(page).get('page'), '1');
    // Changing only the hash query is a same-route navigation, not a remount.
    await page.goto(`${base}#/problems?q=tree`);
    await page.waitForFunction(() => document.querySelector('input[aria-label="Search all problems"]')?.value === 'tree');
    await page.goBack();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Search all problems"]')?.value === 'easy');
    await pages(page).getByText(/Page 2 of /).waitFor();
    assert.equal(page.url(), retainedUrl);
    assert.equal(await cards(page).first().getAttribute('href'), retainedFirst);
    await page.goForward();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Search all problems"]')?.value === 'tree');
    await page.goBack();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Search all problems"]')?.value === 'easy');
    await pages(page).getByText(/Page 2 of /).waitFor();
    assert.equal(bodies.length, 0, `Searching/paging must not fetch solution bodies: ${JSON.stringify(bodies)}`);
    await cards(page).first().click();
    await page.waitForURL(url => url.hash === retainedFirst);
    await page.locator('main pre code').first().waitFor();
    await page.goBack();
    await input(page).waitFor();
    assert.equal(page.url(), retainedUrl);
    assert.equal(await input(page).inputValue(), 'easy');
    assert.equal(await cards(page).first().getAttribute('href'), retainedFirst);
    await input(page).fill('binary tree easy');
    assert.ok(await cards(page).count() > 0);
    await visible(page, 94);
    await input(page).focus();
    await overflow(page);
    await page.screenshot({ path: `${directory}/search-1280-dark.png` });
    await setLight(page);
    await input(page).focus();
    await page.screenshot({ path: `${directory}/search-1280-light.png` });
    await overflow(page);
    results.push({ width: 1280, completeCollection: true, paging: true, filters: true, backAndReload: true, sameRouteHistory: true, rapidTyping: true, filterRace: true, lazyBodies: true, themes: ['dark', 'light'] });
    const mobile = await makePage(390);
    await mobile.goto(`${base}#/problems?page=82`);
    await input(mobile).fill('3934');
    await visible(mobile, 3934);
    await input(mobile).focus();
    await mobile.screenshot({ path: `${directory}/search-390-dark.png` });
    await overflow(mobile);
    await input(mobile).fill('easy');
    await pages(mobile).getByText(/Page 1 of /).waitFor();
    await pages(mobile).getByRole('button', { name: 'Next', exact: true }).tap();
    await pages(mobile).getByText(/Page 2 of /).waitFor();
    assert.equal(params(mobile).get('page'), '1');
    assert.equal(await cards(mobile).count(), 50);
    await mobile.getByRole('button', { name: 'Clear search', exact: true }).tap();
    await pages(mobile).getByText(/Page 1 of /).waitFor();
    assert.equal(params(mobile).has('q'), false);
    assert.equal(params(mobile).has('page'), false);
    await input(mobile).fill('binary tree easy');
    await visible(mobile, 94);
    await setLight(mobile);
    await input(mobile).focus();
    await mobile.screenshot({ path: `${directory}/search-390-light.png` });
    await overflow(mobile);
    results.push({ width: 390, completeCollection: true, paging: true, clear: true, touch: true, themes: ['dark', 'light'] });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, base, results, errors, screenshotDirectory: directory }));
  } finally {
    for (const context of contexts) await context.close();
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
