// Keep the browser's judge adapters identical to the canonical walkthroughs.
const fs = require('node:fs');
const path = require('node:path');
const { root } = require('../walkthroughs/load.cjs');
const { setup, invocation } = require('../walkthroughs/runtime.cjs');
const target = path.join(root, 'src/components/logic/runtime/javascriptAdapter.generated.ts');
const contents = '// Generated by tools/logic/generate-javascript-adapter.cjs. Do not edit by hand.\n'
  + "import type { LogicFixture } from './types';\n\n"
  + `export const setup = ${JSON.stringify(setup)};\n\n`
  + invocation.toString().replace('function invocation(fixture)', 'export function invocation(fixture: LogicFixture): string') + '\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) throw new Error('JavaScript browser judge adapter is stale. Run node tools/logic/generate-javascript-adapter.cjs');
  console.log('JavaScript browser judge adapter matches the canonical fixture runtime.');
} else {
  fs.writeFileSync(target, contents);
  console.log('Generated JavaScript browser judge adapter.');
}
