const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { root, solutionMap } = require('../walkthroughs/load.cjs');

const directory = path.join(root, 'public/solutions');
const manifestPath = path.join(root, 'src/data/solutions/manifest.ts');
const documents = new Map();
const manifest = {};
for (const [id, solution] of Object.entries(solutionMap).sort((a, b) => Number(a[0]) - Number(b[0]))) {
  assert.equal(solution.id, Number(id));
  const content = JSON.stringify(solution) + '\n';
  const hash = crypto.createHash('sha256').update(content).digest('hex').slice(0, 16);
  const file = `${id}-${hash}.json`;
  manifest[id] = file;
  documents.set(file, content);
}
const manifestSource = '// Generated by tools/solutions/generate.cjs. Content is fetched only when opened.\n'
  + 'export const solutionFiles: Record<number, string> = ' + JSON.stringify(manifest, null, 2) + ';\n';
if (process.argv.includes('--write')) {
  fs.mkdirSync(directory, { recursive: true });
  for (const file of fs.readdirSync(directory)) {
    if (file.endsWith('.json') && !documents.has(file)) fs.unlinkSync(path.join(directory, file));
  }
  for (const [file, content] of documents) fs.writeFileSync(path.join(directory, file), content);
  fs.writeFileSync(manifestPath, manifestSource);
} else {
  assert.equal(fs.readFileSync(manifestPath, 'utf8'), manifestSource, 'Curated solution manifest is stale; run npm run solutions:generate');
  assert.deepEqual(fs.readdirSync(directory).filter(file => file.endsWith('.json')).sort(), [...documents.keys()].sort(), 'Missing or obsolete curated solution documents');
  for (const [file, content] of documents) assert.equal(fs.readFileSync(path.join(directory, file), 'utf8'), content, `Stale curated solution: ${file}`);
}
console.log(`Curated solution coverage: ${documents.size} individually loaded documents; all match source.`);
